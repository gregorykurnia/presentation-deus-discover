// The placeholders.md checklist (pure functions; scripts/placeholders.js writes the file).
import { slideLabel, slideTitle, visibleSlides } from './model.js';
import { findPlaceholders } from './placeholders.js';

/** Every string in `value` with its dotted field path, in document order. */
function textFields(value, path = '') {
  if (typeof value === 'string') return [{ field: path, text: value }];
  if (!value || typeof value !== 'object') return [];
  return Object.entries(value).flatMap(([k, v]) => textFields(v, path ? `${path}.${k}` : k));
}

/**
 * Visible slides that contain [placeholders], in deck order:
 * [{ label, slideId, headline, items: [{ text, field, context }] }].
 * A placeholder repeated on one slide is listed once (its first field).
 */
export function placeholdersBySlide(deck) {
  const groups = [];
  for (const slide of visibleSlides(deck)) {
    const seen = new Set();
    const items = [];
    for (const { field, text } of textFields(slide.fields)) {
      for (const ph of findPlaceholders(text)) {
        if (seen.has(ph)) continue;
        seen.add(ph);
        items.push({ text: ph, field, context: text });
      }
    }
    if (items.length) {
      groups.push({
        label: slideLabel(deck, slide.id),
        slideId: slide.id,
        headline: slideTitle(slide),
        items,
      });
    }
  }
  return groups;
}

/**
 * Images on visible slides that will render as the labeled missing box:
 * src null, or a path that `exists(path)` says is not on disk.
 * [{ label, slideId, key, assetLabel, path }] (path null when none is set).
 */
export function missingAssets(deck, exists) {
  const out = [];
  for (const slide of visibleSlides(deck)) {
    for (const [key, img] of Object.entries(slide.images ?? {})) {
      if (!img || typeof img !== 'object') continue;
      const path = typeof img.src === 'string' ? img.src : null;
      if (path && exists(path)) continue;
      out.push({ label: slideLabel(deck, slide.id), slideId: slide.id, key, assetLabel: img.label ?? key, path });
    }
  }
  return out;
}

/** "Slide 9", "Slide A9"; the appendix divider ("A") reads "Appendix divider". */
export function slideName(label) {
  return label === 'A' ? 'Appendix divider' : `Slide ${label}`;
}

/** One slide by name, or several: "Slides A2 to A5" (a run), "Slides 3, 5 and A2". */
export function slidesName(labels) {
  if (labels.length === 1) return slideName(labels[0]);
  const parts = labels.map((l) => /^(A?)(\d+)$/.exec(l));
  const run = parts.every(Boolean) && parts.every((m, i) => i === 0
    || (m[1] === parts[0][1] && Number(m[2]) === Number(parts[i - 1][2]) + 1));
  if (run && labels.length > 2) return `Slides ${labels[0]} to ${labels.at(-1)}`;
  return `Slides ${labels.slice(0, -1).join(', ')} and ${labels.at(-1)}`;
}

/** True when any text field of the slide contains `needle`. */
export function slideHasText(slide, needle) {
  return textFields(slide.fields).some((f) => f.text.includes(needle));
}

/**
 * The "<slide name>: <text>" line of a to-do, or null when it is about no visible
 * slide. A to-do names its slides by `slideId` or by `match(slide)`; one with
 * neither is about the whole deck. Hidden and deleted slides get no to-dos.
 */
function todoLine(deck, todo) {
  if (!todo.slideId && !todo.match) return todo.text;
  const labels = visibleSlides(deck)
    .filter((s) => (todo.match ? todo.match(s) : s.id === todo.slideId))
    .map((s) => slideLabel(deck, s.id));
  return labels.length ? `${slidesName(labels)}: ${todo.text}` : null;
}

const code = (s) => `\`${s}\``;

/**
 * The placeholders.md text.
 * opts.exists(path)   -> is the asset file on disk
 * opts.assetNotes     -> { "<slideId>.<imageKey>": "extra note" } shown under a missing asset
 * opts.extraAssets    -> [{ slideId | match, text }] more asset to-dos (e.g. a screenshot to replace)
 * opts.notes          -> [{ slideId? | match?, text }] notes listed at the end
 * (to-dos about hidden or deleted slides are left out, see todoLine)
 */
export function checklistMarkdown(deck, opts = {}) {
  const { exists = () => false, assetNotes = {}, extraAssets = [], notes = [] } = opts;
  const groups = placeholdersBySlide(deck);
  const assets = missingAssets(deck, exists);
  const total = groups.reduce((n, g) => n + g.items.length, 0);
  const todos = (list) => list.map((t) => todoLine(deck, t)).filter((line) => line != null);
  const extraLines = todos(extraAssets);
  const noteLines = todos(notes);

  const lines = [
    '# Placeholders checklist',
    '',
    'Generated by `npm run placeholders` from `content/deck.json`. Do not edit by hand; re-run after content changes.',
    `Slide numbers match the presenter and the PDF (hidden slides skipped). ${total} placeholders on ${groups.length} slides, ${assets.length + extraLines.length} asset to-dos.`,
    '',
  ];

  for (const g of groups) {
    lines.push(`## ${slideName(g.label)}${g.headline ? `: ${g.headline}` : ''}`, '');
    for (const item of g.items) {
      const ctx = item.context === item.text ? '' : ` in "${item.context}"`;
      lines.push(`- [ ] ${code(item.text)}${ctx} (field ${code(item.field)})`);
    }
    lines.push('');
  }

  lines.push('## Missing assets', '');
  lines.push('These render as a labeled box in the presenter and the PDF until the file is added.', '');
  for (const a of assets) {
    const where = a.path
      ? `expected at ${code(a.path)}`
      : 'no file chosen yet (put it in `assets/` and set its `src` in `content/deck.json`)';
    lines.push(`- [ ] ${slideName(a.label)}: ${a.assetLabel} (image ${code(a.key)}), ${where}`);
    const note = assetNotes[`${a.slideId}.${a.key}`];
    if (note) lines.push(`  - ${note}`);
  }
  for (const line of extraLines) lines.push(`- [ ] ${line}`);
  lines.push('');

  if (noteLines.length) {
    lines.push('## Notes', '');
    for (const line of noteLines) lines.push(`- [ ] ${line}`);
    lines.push('');
  }
  return lines.join('\n');
}
